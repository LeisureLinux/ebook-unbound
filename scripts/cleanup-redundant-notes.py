# 192.168.68.x → 192.0.2.x（保持末位/掩码一致）
n_addr = 0
for f in sorted(SRC.glob("*.md")):
    t = f.read_text()
    new = re.sub(r"192\.168\.68\.(\d+)", r"192.0.2.\1", t)
    new = new.replace("192.168.68.0/24", "192.0.2.0/24")
    new = new.replace("192.168.68.x", "192.0.2.x")
    if new != t:
        c = len(re.findall(r"192\.168\.68", t))
        f.write_text(new)
        n_addr += c
        print(f"  [地址] {f.name}: {c} 处 → 192.0.2.x")
